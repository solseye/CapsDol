export function getCurrentLanguage() {
  const savedLanguage = localStorage.getItem("appLanguage");

  if (SUPPORTED_LANGUAGES.includes(savedLanguage)) {
    return savedLanguage;
  }

  const htmlLanguage = document.documentElement.getAttribute("data-lang");

  if (SUPPORTED_LANGUAGES.includes(htmlLanguage)) {
    return htmlLanguage;
  }

  return "ko";
}

export function setCurrentLanguage(language) {
  const nextLanguage = SUPPORTED_LANGUAGES.includes(language) ? language : "ko";

  localStorage.setItem("appLanguage", nextLanguage);
  document.documentElement.setAttribute("data-lang", nextLanguage);
}

export function translate(language, key, variables = {}) {
  const dictionary = translations[language] || translations.ko;
  const fallbackDictionary = translations.ko;

  const value =
    key.split(".").reduce((acc, part) => acc?.[part], dictionary) ||
    key.split(".").reduce((acc, part) => acc?.[part], fallbackDictionary) ||
    key;

  return Object.entries(variables).reduce(
    (text, [name, replacement]) =>
      text.replaceAll(`{${name}}`, String(replacement)),
    value
  );
}

export function formatTranslatedDate(language, date) {
  return translate(language, "common.yearMonthDay", {
    year: date.getFullYear(),
    month: date.getMonth() + 1,
    day: date.getDate(),
  });
}

export function formatTranslatedMonth(language, date) {
  return translate(language, "common.yearMonth", {
    year: date.getFullYear(),
    month: date.getMonth() + 1,
  });
}
